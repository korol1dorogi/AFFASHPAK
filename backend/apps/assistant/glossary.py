def lookup(term: str) -> tuple[str, str] | None:
    """(canonical term, explanation), or None. Case, «ё» and spaces around «/» do not matter."""
    key = " ".join(term.lower().replace("ё", "е").split())
    key = key.replace(" / ", "/")
    normalized = {name.replace("ё", "е"): name for name in TERMS}
    aliases = {alias.replace("ё", "е"): name for alias, name in ALIASES.items()}
    name = normalized.get(key) or aliases.get(key)
    return None if name is None else (name, TERMS[name])
